CREATE TABLE NXTGEN_NAVIGATION_MASTER (
  ID NUMBER(19) PRIMARY KEY,
  CODE VARCHAR2(80 CHAR) NOT NULL UNIQUE,
  DISPLAY_NAME VARCHAR2(120 CHAR) NOT NULL,
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE
);

CREATE TABLE NXTGEN_NAV_MENU_ACCESS (
  ID NUMBER(19) PRIMARY KEY,
  NAV_ID NUMBER(19) NOT NULL,
  USR_ID VARCHAR2(36 CHAR) NOT NULL,
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE,
  CONSTRAINT NXTGEN_NAV_ACCESS_NAV_FK FOREIGN KEY (NAV_ID) REFERENCES NXTGEN_NAVIGATION_MASTER(ID),
  CONSTRAINT NXTGEN_NAV_ACCESS_USR_FK FOREIGN KEY (USR_ID) REFERENCES NXTGEN_APP_USER_MASTER(ID)
);

