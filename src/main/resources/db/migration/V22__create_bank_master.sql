DECLARE
  table_already_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(table_already_exists, -955);
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE NXTGEN_BANK_MASTER (
      ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      BANK_NAME VARCHAR2(160 CHAR) NOT NULL,
      ACCOUNT_NUMBER_LENGTH NUMBER(2) NOT NULL,
      IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
      CRE_BY VARCHAR2(120 CHAR) NOT NULL,
      CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      UPD_BY VARCHAR2(120 CHAR),
      UPD_DATE TIMESTAMP WITH TIME ZONE,
      CONSTRAINT NXTGEN_BANK_NAME_UK UNIQUE (BANK_NAME),
      CONSTRAINT NXTGEN_BANK_ACCOUNT_LENGTH_CK CHECK (ACCOUNT_NUMBER_LENGTH BETWEEN 9 AND 18)
    )
  ]';
EXCEPTION
  WHEN table_already_exists THEN NULL;
END;
/

MERGE INTO NXTGEN_BANK_MASTER target
USING (
  SELECT 'HDFC Bank' BANK_NAME, 14 ACCOUNT_NUMBER_LENGTH FROM DUAL UNION ALL
  SELECT 'SBI Bank', 11 FROM DUAL UNION ALL
  SELECT 'ICICI Bank', 12 FROM DUAL UNION ALL
  SELECT 'Axis Bank', 15 FROM DUAL UNION ALL
  SELECT 'Kotak Mahindra Bank', 14 FROM DUAL UNION ALL
  SELECT 'Punjab National Bank', 16 FROM DUAL UNION ALL
  SELECT 'Canara Bank', 13 FROM DUAL UNION ALL
  SELECT 'Bank of Baroda', 14 FROM DUAL
) source
ON (target.BANK_NAME = source.BANK_NAME)
WHEN MATCHED THEN UPDATE SET
  target.ACCOUNT_NUMBER_LENGTH = source.ACCOUNT_NUMBER_LENGTH,
  target.IS_ACTIVE = 'Y',
  target.UPD_BY = 'SYSTEM',
  target.UPD_DATE = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (BANK_NAME, ACCOUNT_NUMBER_LENGTH, IS_ACTIVE, CRE_BY)
  VALUES (source.BANK_NAME, source.ACCOUNT_NUMBER_LENGTH, 'Y', 'SYSTEM');
