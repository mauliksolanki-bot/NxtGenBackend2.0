CREATE TABLE NXTGEN_ROLE_MASTER (
  ID NUMBER(19) PRIMARY KEY,
  ROLE_NAME VARCHAR2(120 CHAR) NOT NULL UNIQUE,
  ROLE_DESC VARCHAR2(500 CHAR),
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE
);

CREATE TABLE NXTGEN_APP_USER_MASTER (
  ID VARCHAR2(36 CHAR) PRIMARY KEY,
  EMP_ID VARCHAR2(20 CHAR) NOT NULL,
  EMP_FNAME VARCHAR2(120 CHAR) NOT NULL,
  EMP_LNAME VARCHAR2(120 CHAR) NOT NULL,
  EMP_EMAIL VARCHAR2(254 CHAR) NOT NULL UNIQUE,
  HASH_PASSWORD VARCHAR2(100 CHAR) NOT NULL,
  PRIMARY_ROLE_ID NUMBER(19) NOT NULL,
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE,
  CONSTRAINT NXTGEN_APP_USER_ROLE_FK FOREIGN KEY (PRIMARY_ROLE_ID) REFERENCES NXTGEN_ROLE_MASTER(ID),
  CONSTRAINT NXTGEN_APP_USER_EMP_ID_CK CHECK (REGEXP_LIKE(EMP_ID, '^[0-9]{6,}$')),
  CONSTRAINT NXTGEN_APP_USER_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y', 'N'))
);

