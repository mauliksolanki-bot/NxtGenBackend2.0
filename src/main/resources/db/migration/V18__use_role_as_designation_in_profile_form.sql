UPDATE NXTGEN_FORM_FIELDS_MASTER
SET FIELD_NAME = 'Designation', UPD_BY = 'SYSTEM', UPD_DATE = SYSTIMESTAMP
WHERE FORM_ID = 1 AND FIELD_CODE = 'PRIMARY_ROLE';

UPDATE NXTGEN_FORM_FIELDS_MASTER
SET IS_ACTIVE = 'N', UPD_BY = 'SYSTEM', UPD_DATE = SYSTIMESTAMP
WHERE FORM_ID = 1 AND FIELD_CODE = 'DESIGNATION';

INSERT INTO NXTGEN_FORM_FIELDS_MASTER (
  ID, FORM_ID, FIELD_CODE, FIELD_NAME, FIELD_TYPE, IS_MANDATORY, IS_ACTIVE, CRE_BY
)
SELECT NVL(MAX(existing_field.ID), 0) + 1, 1, 'DESIGNATION_LEVEL', 'Designation Level', 'TEXTBOX', 'N', 'Y', 'SYSTEM'
FROM NXTGEN_FORM_FIELDS_MASTER existing_field
HAVING NOT EXISTS (
  SELECT 1
  FROM NXTGEN_FORM_FIELDS_MASTER
  WHERE FORM_ID = 1 AND FIELD_CODE = 'DESIGNATION_LEVEL'
);
