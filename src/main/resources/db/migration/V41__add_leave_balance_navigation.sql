INSERT INTO WF_NAVIGATION_MASTER (ID, CODE, DISPLAY_NAME, IS_PARENT, PARENT_NAV_ID, DISPLAY_ORDER, IS_ACTIVE, CRE_BY)
SELECT (SELECT NVL(MAX(existing_navigation.ID), 0) + 1 FROM WF_NAVIGATION_MASTER existing_navigation), 'LEAVE_BALANCE', 'Leave Balance', 'N',
       (SELECT parent_navigation.ID FROM WF_NAVIGATION_MASTER parent_navigation WHERE parent_navigation.CODE = 'LEAVE_MANAGEMENT'),
       7, 'Y', 'SYSTEM'
FROM DUAL
WHERE EXISTS (SELECT 1 FROM WF_NAVIGATION_MASTER WHERE CODE = 'LEAVE_MANAGEMENT')
  AND NOT EXISTS (SELECT 1 FROM WF_NAVIGATION_MASTER WHERE CODE = 'LEAVE_BALANCE');

INSERT INTO WF_NAV_MENU_ACCESS (ID, NAV_ID, USR_ID, IS_ACTIVE, CRE_BY)
SELECT (SELECT NVL(MAX(access_row.ID), 0) FROM WF_NAV_MENU_ACCESS access_row) + ROW_NUMBER() OVER (ORDER BY user_account.ID), navigation.ID, user_account.ID, 'Y', 'SYSTEM'
FROM WF_NAVIGATION_MASTER navigation
INNER JOIN WF_APP_USER_MASTER user_account ON user_account.IS_ACTIVE = 'Y'
WHERE navigation.CODE = 'LEAVE_BALANCE'
  AND NOT EXISTS (
    SELECT 1 FROM WF_NAV_MENU_ACCESS access_row
    WHERE access_row.NAV_ID = navigation.ID AND access_row.USR_ID = user_account.ID
  );
