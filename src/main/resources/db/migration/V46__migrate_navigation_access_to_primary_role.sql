CREATE TABLE WF_NAV_ACCESS_ROLE_BACKUP AS
SELECT DISTINCT ACCESS_ROW.NAV_ID, USER_ACCOUNT.PRIMARY_ROLE_ID, ACCESS_ROW.IS_ACTIVE, ACCESS_ROW.CRE_BY
FROM WF_NAV_MENU_ACCESS ACCESS_ROW
INNER JOIN WF_APP_USER_MASTER USER_ACCOUNT ON USER_ACCOUNT.ID = ACCESS_ROW.USR_ID
WHERE USER_ACCOUNT.PRIMARY_ROLE_ID IS NOT NULL;

DELETE FROM WF_NAV_MENU_ACCESS;

ALTER TABLE WF_NAV_MENU_ACCESS DROP COLUMN USR_ID CASCADE CONSTRAINTS;
ALTER TABLE WF_NAV_MENU_ACCESS ADD (PRIMARY_ROLE_ID NUMBER(19));
ALTER TABLE WF_NAV_MENU_ACCESS ADD CONSTRAINT WF_NAV_ACCESS_ROLE_FK FOREIGN KEY (PRIMARY_ROLE_ID) REFERENCES WF_ROLE_MASTER(ID);

INSERT INTO WF_NAV_MENU_ACCESS (ID, NAV_ID, PRIMARY_ROLE_ID, IS_ACTIVE, CRE_BY)
SELECT ROW_NUMBER() OVER (ORDER BY NAV_ID, PRIMARY_ROLE_ID), NAV_ID, PRIMARY_ROLE_ID, IS_ACTIVE, CRE_BY
FROM WF_NAV_ACCESS_ROLE_BACKUP;

ALTER TABLE WF_NAV_MENU_ACCESS MODIFY (PRIMARY_ROLE_ID NOT NULL);
ALTER TABLE WF_NAV_MENU_ACCESS ADD CONSTRAINT WF_NAV_ACCESS_NAV_ROLE_UK UNIQUE (NAV_ID, PRIMARY_ROLE_ID);

DROP TABLE WF_NAV_ACCESS_ROLE_BACKUP PURGE;
