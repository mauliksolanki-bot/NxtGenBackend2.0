CREATE TABLE WF_USER_AUDIT_MASTER (
  ID VARCHAR2(36 CHAR) PRIMARY KEY,
  EMP_ID VARCHAR2(36 CHAR),
  ACTIVITY_CATEGORY VARCHAR2(80 CHAR) NOT NULL,
  ACTIVITY_ACTION VARCHAR2(120 CHAR) NOT NULL,
  ACTIVITY_DETAILS VARCHAR2(1000 CHAR) NOT NULL,
  ACTIVITY_STATUS VARCHAR2(20 CHAR) DEFAULT 'SUCCESS' NOT NULL CHECK (ACTIVITY_STATUS IN ('SUCCESS','FAILED','PENDING')),
  ACTIVITY_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  IP_ADDRESS VARCHAR2(64 CHAR),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX WF_USER_AUDIT_EMP_IDX ON WF_USER_AUDIT_MASTER (EMP_ID, ACTIVITY_AT);
CREATE INDEX WF_USER_AUDIT_CATEGORY_IDX ON WF_USER_AUDIT_MASTER (ACTIVITY_CATEGORY, ACTIVITY_AT);

DELETE FROM WF_NAV_MENU_ACCESS
WHERE NAV_ID IN (SELECT ID FROM WF_NAVIGATION_MASTER WHERE CODE IN ('AUDIT', 'USER_ACCESS'))
  AND PRIMARY_ROLE_ID <> (SELECT ID FROM WF_ROLE_MASTER WHERE ROLE_NAME = 'Administrator');
