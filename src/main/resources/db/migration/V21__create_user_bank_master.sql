CREATE TABLE NXTGEN_USR_BANK_MASTER (
  ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMP_ID VARCHAR2(20 CHAR) NOT NULL,
  ACCOUNT_NUMBER VARCHAR2(18 CHAR) NOT NULL,
  IFSC_CODE VARCHAR2(11 CHAR) NOT NULL,
  BANK_NAME VARCHAR2(160 CHAR) NOT NULL,
  BRANCH_NAME VARCHAR2(160 CHAR) NOT NULL,
  ACCOUNT_TYPE VARCHAR2(30 CHAR) NOT NULL,
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE,
  CONSTRAINT NXTGEN_USR_BANK_EMP_UK UNIQUE (EMP_ID),
  CONSTRAINT NXTGEN_USR_BANK_EMP_FK FOREIGN KEY (EMP_ID) REFERENCES NXTGEN_APP_USER_MASTER(EMP_ID),
  CONSTRAINT NXTGEN_USR_BANK_ACCOUNT_CK CHECK (REGEXP_LIKE(ACCOUNT_NUMBER, '^[0-9]{9,18}$')),
  CONSTRAINT NXTGEN_USR_BANK_IFSC_CK CHECK (REGEXP_LIKE(IFSC_CODE, '^[A-Z]{4}0[A-Z0-9]{6}$')),
  CONSTRAINT NXTGEN_USR_BANK_TYPE_CK CHECK (ACCOUNT_TYPE IN ('Salary Account', 'Savings Account', 'Current Account'))
);
