DECLARE
  column_exists NUMBER;
  constraint_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO column_exists FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'WF_NAVIGATION_MASTER' AND COLUMN_NAME = 'IS_PARENT';
  IF column_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE WF_NAVIGATION_MASTER ADD (IS_PARENT CHAR(1 CHAR) DEFAULT ''N'' NOT NULL CHECK (IS_PARENT IN (''Y'', ''N'')), PARENT_NAV_ID NUMBER(19))';
  END IF;

  SELECT COUNT(*) INTO constraint_exists FROM USER_CONSTRAINTS
  WHERE CONSTRAINT_NAME = 'WF_NAVIGATION_PARENT_FK';
  IF constraint_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE WF_NAVIGATION_MASTER ADD CONSTRAINT WF_NAVIGATION_PARENT_FK FOREIGN KEY (PARENT_NAV_ID) REFERENCES WF_NAVIGATION_MASTER(ID)';
  END IF;
END;
/

INSERT INTO WF_NAVIGATION_MASTER (ID, CODE, DISPLAY_NAME, IS_PARENT, PARENT_NAV_ID, DISPLAY_ORDER, IS_ACTIVE, CRE_BY)
SELECT NVL(MAX(ID), 0) + 1, 'LEAVE_MANAGEMENT', 'Leave Management', 'Y', NULL, 5, 'Y', 'SYSTEM'
FROM WF_NAVIGATION_MASTER
WHERE NOT EXISTS (SELECT 1 FROM WF_NAVIGATION_MASTER WHERE CODE = 'LEAVE_MANAGEMENT');

INSERT INTO WF_NAVIGATION_MASTER (ID, CODE, DISPLAY_NAME, IS_PARENT, PARENT_NAV_ID, DISPLAY_ORDER, IS_ACTIVE, CRE_BY)
SELECT (SELECT NVL(MAX(existing_navigation.ID), 0) + 1 FROM WF_NAVIGATION_MASTER existing_navigation), 'APPLY_LEAVE', 'Apply Leave', 'N',
       (SELECT parent_navigation.ID FROM WF_NAVIGATION_MASTER parent_navigation WHERE parent_navigation.CODE = 'LEAVE_MANAGEMENT'),
       6, 'Y', 'SYSTEM'
FROM DUAL
WHERE EXISTS (SELECT 1 FROM WF_NAVIGATION_MASTER WHERE CODE = 'LEAVE_MANAGEMENT')
  AND NOT EXISTS (SELECT 1 FROM WF_NAVIGATION_MASTER WHERE CODE = 'APPLY_LEAVE');

INSERT INTO WF_NAV_MENU_ACCESS (ID, NAV_ID, USR_ID, IS_ACTIVE, CRE_BY)
SELECT (SELECT NVL(MAX(access_row.ID), 0) FROM WF_NAV_MENU_ACCESS access_row) + ROW_NUMBER() OVER (ORDER BY user_account.ID), navigation.ID, user_account.ID, 'Y', 'SYSTEM'
FROM WF_NAVIGATION_MASTER navigation
INNER JOIN WF_APP_USER_MASTER user_account ON user_account.IS_ACTIVE = 'Y'
WHERE navigation.CODE IN ('LEAVE_MANAGEMENT', 'APPLY_LEAVE')
  AND NOT EXISTS (
    SELECT 1 FROM WF_NAV_MENU_ACCESS access_row
    WHERE access_row.NAV_ID = navigation.ID AND access_row.USR_ID = user_account.ID
  );
