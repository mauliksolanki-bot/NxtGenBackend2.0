CREATE TABLE NXTGEN_FORM_MASTER (
  ID NUMBER(19) PRIMARY KEY, FORM_CODE VARCHAR2(80 CHAR) NOT NULL UNIQUE,
  FORM_NAME VARCHAR2(160 CHAR) NOT NULL, IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL, CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR), UPD_DATE TIMESTAMP WITH TIME ZONE
);
CREATE TABLE NXTGEN_FORM_FIELDS_MASTER (
  ID NUMBER(19) PRIMARY KEY, FORM_ID NUMBER(19) NOT NULL, FIELD_CODE VARCHAR2(80 CHAR) NOT NULL,
  FIELD_NAME VARCHAR2(160 CHAR) NOT NULL, FIELD_TYPE VARCHAR2(40 CHAR) NOT NULL,
  IS_MANDATORY CHAR(1 CHAR) DEFAULT 'N' NOT NULL CHECK (IS_MANDATORY IN ('Y','N')),
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CRE_BY VARCHAR2(120 CHAR) NOT NULL, CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR), UPD_DATE TIMESTAMP WITH TIME ZONE,
  CONSTRAINT NXTGEN_FORM_FIELD_FORM_FK FOREIGN KEY (FORM_ID) REFERENCES NXTGEN_FORM_MASTER(ID),
  CONSTRAINT NXTGEN_FORM_FIELD_CODE_UK UNIQUE (FORM_ID, FIELD_CODE)
);
