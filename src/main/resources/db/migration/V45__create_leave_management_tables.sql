CREATE TABLE WF_LEAVE_CATEGORY (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LEAVE_TYPE VARCHAR2(80 CHAR) NOT NULL UNIQUE,
  DEFAULT_LEAVE NUMBER(5) NOT NULL CHECK (DEFAULT_LEAVE >= 0),
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE WF_LEAVE_MASTER (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMP_ID VARCHAR2(36 CHAR) NOT NULL,
  LEAVE_TYPE VARCHAR2(80 CHAR) NOT NULL,
  TOTAL_LEAVE NUMBER(5) NOT NULL CHECK (TOTAL_LEAVE >= 0),
  AVAILABLE_LEAVE NUMBER(5) NOT NULL CHECK (AVAILABLE_LEAVE >= 0),
  CONSTRAINT WF_LEAVE_MASTER_UK UNIQUE (EMP_ID, LEAVE_TYPE),
  CONSTRAINT WF_LEAVE_MASTER_CATEGORY_FK FOREIGN KEY (LEAVE_TYPE) REFERENCES WF_LEAVE_CATEGORY(LEAVE_TYPE)
);

CREATE TABLE WF_DOCUMENT_CENTER (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMP_ID VARCHAR2(36 CHAR) NOT NULL,
  DOC_TYPE VARCHAR2(80 CHAR) NOT NULL,
  DOC_NAME VARCHAR2(255 CHAR) NOT NULL,
  MIME_TYPE VARCHAR2(100 CHAR) NOT NULL,
  DOC_CONTENT BLOB NOT NULL,
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE,
  IS_DELETED CHAR(1 CHAR) DEFAULT 'N' NOT NULL CHECK (IS_DELETED IN ('Y','N'))
);

CREATE TABLE WF_LEAVE_APPLICATIONS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMP_ID VARCHAR2(36 CHAR) NOT NULL,
  LEAVE_TYPE VARCHAR2(80 CHAR) NOT NULL,
  FROM_DATE DATE NOT NULL,
  TO_DATE DATE NOT NULL,
  REASON VARCHAR2(1000 CHAR) NOT NULL,
  DOCUMENT_ID NUMBER,
  CRE_BY VARCHAR2(120 CHAR) NOT NULL,
  CRE_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPD_BY VARCHAR2(120 CHAR),
  UPD_DATE TIMESTAMP WITH TIME ZONE,
  IS_APPROVED CHAR(1 CHAR) DEFAULT 'N' NOT NULL CHECK (IS_APPROVED IN ('Y','N')),
  APPROVED_BY VARCHAR2(120 CHAR),
  CONSTRAINT WF_LEAVE_APPLICATION_DATE_CK CHECK (TO_DATE >= FROM_DATE),
  CONSTRAINT WF_LEAVE_APPLICATION_CATEGORY_FK FOREIGN KEY (LEAVE_TYPE) REFERENCES WF_LEAVE_CATEGORY(LEAVE_TYPE),
  CONSTRAINT WF_LEAVE_APPLICATION_DOC_FK FOREIGN KEY (DOCUMENT_ID) REFERENCES WF_DOCUMENT_CENTER(ID)
);

CREATE TABLE WF_HOLIDAY_CALENDAR (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  HOLIDAY_NAME VARCHAR2(180 CHAR) NOT NULL,
  ON_DATE DATE NOT NULL,
  IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CONSTRAINT WF_HOLIDAY_CALENDAR_UK UNIQUE (ON_DATE)
);

